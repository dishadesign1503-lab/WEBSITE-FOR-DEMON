// Generates ../plan-data.js from the game's own floor-plan data (read only).
// Usage: node scripts/build-plan-data.mjs <path to the game repo>

import fs from 'node:fs'
import path from 'node:path'
import { pathToFileURL } from 'node:url'

const game = path.resolve(process.argv[2] ?? '../Dishadesign1503/ai-in-design-main/ai-in-design-main')
const world = (f) => pathToFileURL(path.join(game, 'src/house/world', f)).href
const { X_REST, Y_REST, buildConfig, wallUnits } = await import(world('plan.js'))
const { CONFIGS, LAYOUTS } = await import(world('layouts.js'))

const configs = {}
for (const id of ['origin', 'courtSouth', 'spineEast', 'branches', 'ring', 'bands', 'strips', 'span']) {
  const cfg = buildConfig(id, { ...CONFIGS[id], exits: LAYOUTS.origin.exits })
  if (cfg.problems.length) throw new Error(`${id}: ${cfg.problems.join(', ')}`)
  const walls = {}
  for (const [key, w] of wallUnits(cfg)) walls[key] = w.exterior ? 'e' : 'i'
  const open = (type) => [...cfg.openings].filter(([, o]) => o.type === type).map(([k]) => k)
  configs[id] = { label: cfg.label, walls, doors: open('door'), windows: open('window'), exits: open('exit') }
}

const out = `// Generated by scripts/build-plan-data.mjs from the game's src/house/world/plan.js and layouts.js.
// Do not edit by hand.
window.PLAN_DATA = ${JSON.stringify({ X: X_REST, Y: Y_REST, body: LAYOUTS.origin.body, configs })};
`
fs.writeFileSync(new URL('../plan-data.js', import.meta.url), out)
console.log('plan-data.js:', Object.keys(configs).join(', '), `${out.length} bytes`)
